/** Storage sizes that exact model shipped in. Empty until a model is picked. */
export const getMobileStorageOptions = (brand: string, model: string): string[] => {
  if (!model) return [];
  // "Other" is an unlisted phone, so it gets the full common range.
  if (model === MOBILE_OTHER) return ['64 GB', '128 GB', '256 GB', '512 GB', '1 TB', '2 TB'];
  return MOBILE_STORAGE[model] ?? ['128 GB', '256 GB'];
};
