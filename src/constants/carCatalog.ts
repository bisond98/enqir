/** Trims the brand + model actually came in; empty when unknown, so the form
 *  shows the free-text Variant box instead of an empty dropdown. */
const CAR_VARIANTS_LOOKUP: Record<string, string[]> = Object.fromEntries(
  Object.entries(CAR_VARIANTS).map(([key, value]) => [key.toLowerCase(), value]),
);

export function getCarVariants(brand: string, model: string): string[] {
  if (!brand || !model) return [];
  // Case- and spacing-insensitive: "maruti suzuki | swift" resolves like
  // "Maruti Suzuki|Swift", so the dropdown is not limited to perfectly-matched
  // catalogue picks.
  const key = `${brand.trim()}|${model.trim()}`.toLowerCase().replace(/\s+/g, ' ');
  return CAR_VARIANTS[`${brand.trim()}|${model.trim()}`] ?? CAR_VARIANTS_LOOKUP[key] ?? [];
}
